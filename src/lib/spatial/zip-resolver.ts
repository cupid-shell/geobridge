/**
 * Resolves any US 5-digit ZIP code to a [longitude, latitude] centroid.
 * Falls back to 3-digit sectional center facility if exact 5-digit is not mapped.
 */
export function resolveZipToCoordinates(input: any): [number, number] | null {
  const cleanZip = sanitizePostalCode(input);
  if (!cleanZip || cleanZip.length < 3) return null;

  const prefix3 = cleanZip.substring(0, 3);
  if (US_SCF_CENTROIDS[prefix3]) {
    return US_SCF_CENTROIDS[prefix3];
  }

  // Broad state approximation fallback for unlisted prefixes
  const firstDigit = parseInt(cleanZip[0], 10);
  switch (firstDigit) {
    case 0: return [-71.50, 42.50]; // New England
    case 1: return [-74.00, 41.00]; // NY / PA
    case 2: return [-77.50, 37.50]; // Mid-Atlantic
    case 3: return [-83.50, 32.50]; // Southeast
    case 4: return [-84.50, 40.50]; // OH / IN / MI / KY
    case 5: return [-92.50, 45.00]; // Upper Midwest
    case 6: return [-89.00, 40.00]; // IL / MO / KS
    case 7: return [-96.50, 32.00]; // TX / LA / OK / AR
    case 8: return [-108.00, 38.00]; // Mountain West
    case 9: return [-120.00, 37.00]; // Pacific West
    default: return null;
  }
}
